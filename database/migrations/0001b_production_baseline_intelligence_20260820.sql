CREATE TABLE public.site_intelligence_gsc_observations (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  source_import_id text NOT NULL,
  period_start date NOT NULL,
  period_end date NOT NULL,
  page_path text NOT NULL,
  query text DEFAULT ''::text NOT NULL,
  asset_id text,
  owner_keyword text,
  owner_asset_id text,
  owner_status text DEFAULT 'not_evaluated'::text NOT NULL,
  clicks bigint DEFAULT 0 NOT NULL,
  impressions bigint DEFAULT 0 NOT NULL,
  ctr numeric(12,8) DEFAULT 0 NOT NULL,
  "position" numeric(12,4),
  row_fingerprint text NOT NULL,
  captured_at timestamp with time zone DEFAULT now() NOT NULL,
  metadata jsonb DEFAULT '{}'::jsonb NOT NULL,
  CONSTRAINT site_intelligence_gsc_observations_owner_status_check CHECK (owner_status = ANY (ARRAY['matched'::text, 'mismatch'::text, 'unowned'::text, 'unmapped'::text, 'not_evaluated'::text])),
  CONSTRAINT site_intelligence_gsc_observations_clicks_check CHECK (clicks >= 0),
  CONSTRAINT site_intelligence_gsc_observations_impressions_check CHECK (impressions >= 0),
  CONSTRAINT site_intelligence_gsc_observations_ctr_check CHECK (ctr >= 0::numeric),
  CONSTRAINT site_intelligence_gsc_observations_position_check CHECK ("position" IS NULL OR "position" >= 0::numeric),
  CONSTRAINT site_intelligence_gsc_observations_check CHECK (period_end >= period_start),
  CONSTRAINT site_intelligence_gsc_observations_pkey PRIMARY KEY (id),
  CONSTRAINT site_intelligence_gsc_observa_period_start_period_end_page__key UNIQUE (period_start, period_end, page_path, query),
  CONSTRAINT site_intelligence_gsc_observations_source_import_id_fkey FOREIGN KEY (source_import_id) REFERENCES site_intelligence_import_runs(import_id) ON DELETE RESTRICT
);

CREATE TABLE public.site_intelligence_relationships (
  relationship_id text NOT NULL,
  from_kind text NOT NULL,
  from_key text NOT NULL,
  relationship_type text NOT NULL,
  to_kind text NOT NULL,
  to_key text NOT NULL,
  basis text NOT NULL,
  source_import_id text,
  status text DEFAULT 'active'::text NOT NULL,
  first_seen_at timestamp with time zone DEFAULT now() NOT NULL,
  last_seen_at timestamp with time zone DEFAULT now() NOT NULL,
  metadata jsonb DEFAULT '{}'::jsonb NOT NULL,
  updated_at timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT site_intelligence_relationships_from_kind_check CHECK (from_kind = ANY (ARRAY['asset'::text, 'keyword'::text, 'path'::text])),
  CONSTRAINT site_intelligence_relationships_relationship_type_check CHECK (relationship_type = ANY (ARRAY['belongs_to'::text, 'references'::text, 'solves'::text, 'supports'::text, 'has_evidence'::text, 'owned_by'::text, 'related_to'::text, 'canonical_to'::text, 'redirects_to'::text, 'replaces'::text])),
  CONSTRAINT site_intelligence_relationships_to_kind_check CHECK (to_kind = ANY (ARRAY['asset'::text, 'keyword'::text, 'path'::text])),
  CONSTRAINT site_intelligence_relationships_basis_check CHECK (basis = ANY (ARRAY['metadata'::text, 'registry'::text, 'content_link'::text, 'keyword_owner'::text, 'runtime_evidence'::text, 'manual'::text])),
  CONSTRAINT site_intelligence_relationships_status_check CHECK (status = ANY (ARRAY['active'::text, 'stale'::text, 'rejected'::text])),
  CONSTRAINT site_intelligence_relationships_check CHECK (NOT (from_kind = to_kind AND from_key = to_key)),
  CONSTRAINT site_intelligence_relationships_pkey PRIMARY KEY (relationship_id),
  CONSTRAINT site_intelligence_relationshi_from_kind_from_key_relationsh_key UNIQUE (from_kind, from_key, relationship_type, to_kind, to_key),
  CONSTRAINT site_intelligence_relationships_source_import_id_fkey FOREIGN KEY (source_import_id) REFERENCES site_intelligence_import_runs(import_id) ON DELETE SET NULL
);

CREATE TABLE public.site_intelligence_snapshots (
  snapshot_id text NOT NULL,
  snapshot_type text NOT NULL,
  generated_at timestamp with time zone NOT NULL,
  source_generated_at timestamp with time zone,
  window_days integer,
  summary jsonb DEFAULT '{}'::jsonb NOT NULL,
  payload jsonb DEFAULT '{}'::jsonb NOT NULL,
  input_fingerprint text,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT site_intelligence_snapshots_snapshot_type_check CHECK (snapshot_type = ANY (ARRAY['signals'::text, 'action_queue'::text])),
  CONSTRAINT site_intelligence_snapshots_window_days_check CHECK (window_days IS NULL OR window_days >= 1 AND window_days <= 365),
  CONSTRAINT site_intelligence_snapshots_pkey PRIMARY KEY (snapshot_id)
);
