-- Continuation of the 2026-08-20 production schema baseline.

CREATE TABLE public.search_clicks (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  search_query_id bigint,
  anonymous_id text,
  session_id text,
  query text NOT NULL,
  result_id text,
  result_type text,
  result_href text NOT NULL,
  "position" integer,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT search_clicks_pkey PRIMARY KEY (id),
  CONSTRAINT search_clicks_search_query_id_fkey FOREIGN KEY (search_query_id) REFERENCES search_queries(id) ON DELETE SET NULL,
  CONSTRAINT search_clicks_position_nonnegative CHECK ("position" >= 0)
);

CREATE TABLE public.site_intelligence_action_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  action_id text NOT NULL,
  event_type text NOT NULL,
  from_status text,
  to_status text,
  note text,
  metrics jsonb DEFAULT '{}'::jsonb NOT NULL,
  metadata jsonb DEFAULT '{}'::jsonb NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT site_intelligence_action_events_pkey PRIMARY KEY (id),
  CONSTRAINT site_intelligence_action_events_action_id_fkey FOREIGN KEY (action_id) REFERENCES site_intelligence_actions(action_id) ON DELETE CASCADE,
  CONSTRAINT site_intelligence_action_events_event_type_check CHECK (event_type = ANY (ARRAY['created'::text, 'seen'::text, 'status_change'::text, 'note'::text, 'before_snapshot'::text, 'after_snapshot'::text, 'review'::text, 'due_date_change'::text, 'relationship_change'::text, 'reopened'::text]))
);

CREATE TABLE public.site_intelligence_action_links (
  from_action_id text NOT NULL,
  relationship_type text NOT NULL,
  to_action_id text NOT NULL,
  note text,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT site_intelligence_action_links_relationship_type_check CHECK (relationship_type = ANY (ARRAY['related'::text, 'blocks'::text, 'duplicate_of'::text, 'follow_up'::text])),
  CONSTRAINT site_intelligence_action_links_check CHECK (from_action_id <> to_action_id),
  CONSTRAINT site_intelligence_action_links_pkey PRIMARY KEY (from_action_id, relationship_type, to_action_id),
  CONSTRAINT site_intelligence_action_links_from_action_id_fkey FOREIGN KEY (from_action_id) REFERENCES site_intelligence_actions(action_id) ON DELETE CASCADE,
  CONSTRAINT site_intelligence_action_links_to_action_id_fkey FOREIGN KEY (to_action_id) REFERENCES site_intelligence_actions(action_id) ON DELETE CASCADE
);

